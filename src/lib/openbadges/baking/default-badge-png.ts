const crcTable = (() => {
  const table: number[] = [];
  for (let i = 0; i < 256; i += 1) {
    let c = i;
    for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[i] = c >>> 0;
  }
  return table;
})();

function crc32(buffer: Buffer) {
  let crc = 0xffffffff;
  for (const byte of buffer) crc = crcTable[(crc ^ byte) & 0xff] ^ (crc >>> 8);
  return (crc ^ 0xffffffff) >>> 0;
}

function chunk(type: string, data: Buffer) {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length, 0);
  const typeAndData = Buffer.concat([Buffer.from(type), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(typeAndData), 0);
  return Buffer.concat([length, typeAndData, crc]);
}

function setPixel(pixels: Buffer, x: number, y: number, color: number[]) {
  if (x < 0 || y < 0 || x >= WIDTH || y >= HEIGHT) return;
  const offset = (y * WIDTH + x) * 3;
  pixels[offset] = color[0];
  pixels[offset + 1] = color[1];
  pixels[offset + 2] = color[2];
}

function fillRect(pixels: Buffer, x: number, y: number, width: number, height: number, color: number[]) {
  for (let row = 0; row < height; row += 1) {
    for (let col = 0; col < width; col += 1) setPixel(pixels, x + col, y + row, color);
  }
}

function drawGlyph(pixels: Buffer, glyph: number[], x: number, y: number, scale: number, color: number[]) {
  glyph.forEach((row, rowIndex) => {
    for (let col = 0; col < 5; col += 1) {
      if ((row & (1 << (4 - col))) === 0) continue;
      fillRect(pixels, x + col * scale, y + rowIndex * scale, scale, scale, color);
    }
  });
}

function wrapName(name: string): string[] {
  const words = name.toUpperCase().replace(/[^A-Z0-9 -]/g, " ").replace(/\s+/g, " ").trim().split(" ");
  const lines: string[] = [];
  let current = "";
  for (const word of words) {
    const next = current ? `${current} ${word}` : word;
    if (next.length > 18 && current) {
      lines.push(current);
      current = word;
    } else {
      current = next;
    }
  }
  if (current) lines.push(current);
  return lines.slice(0, 4);
}

export function renderDefaultBadgePng(name: string): Buffer {
  const pixels = Buffer.alloc(WIDTH * HEIGHT * 3);
  for (let i = 0; i < pixels.length; i += 3) {
    pixels[i] = VIOLET[0];
    pixels[i + 1] = VIOLET[1];
    pixels[i + 2] = VIOLET[2];
  }

  const radius = 86;
  const centerX = WIDTH / 2;
  const centerY = 230;
  for (let y = centerY - radius; y <= centerY + radius; y += 1) {
    for (let x = centerX - radius; x <= centerX + radius; x += 1) {
      const dx = x - centerX;
      const dy = y - centerY;
      if (dx * dx + dy * dy <= radius * radius) setPixel(pixels, x, y, EMBLEM);
    }
  }
  drawGlyph(pixels, GLYPHS.B, centerX - 20, centerY - 28, 8, INK);

  const lines = wrapName(name || "Open Badge");
  const scale = 4;
  const lineHeight = 7 * scale + 12;
  lines.forEach((line, index) => {
    const width = line.length * (5 * scale + scale) - scale;
    let cursor = Math.round((WIDTH - width) / 2);
    const y = 390 + index * lineHeight;
    for (const character of line) {
      drawGlyph(pixels, GLYPHS[character] ?? GLYPHS[" "], cursor, y, scale, PAPER);
      cursor += 5 * scale + scale;
    }
  });

  const stride = WIDTH * 3 + 1;
  const raw = Buffer.alloc(stride * HEIGHT);
  for (let y = 0; y < HEIGHT; y += 1) {
    pixels.copy(raw, y * stride + 1, y * WIDTH * 3, (y + 1) * WIDTH * 3);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(WIDTH, 0);
  ihdr.writeUInt32BE(HEIGHT, 4);
  ihdr[8] = 8;
  ihdr[9] = 2;
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", zlib.deflateSync(raw)),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}
